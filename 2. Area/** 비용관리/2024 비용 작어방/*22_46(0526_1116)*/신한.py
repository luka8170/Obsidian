import openpyxl

# 엑셀 파일 생성
wb = openpyxl.Workbook()
sheet = wb.active
sheet.title = "데이터"

# 헤더 작성
headers = ["연도", "월", "일", "Week number", "사용처", "승인번호", "승인금액", "승인취소여부", "카드이용시간", "카드사"]
sheet.append(headers)

# 데이터 입력
data = [
    [2024, 11, 15, 46, "티머니 개인택시", 49993557, 9400, "아니오", "08:42", "비자카드"],
    [2024, 11, 14, 46, "플레이팅 김포공항점", 44344303, 10500, "아니오", "17:51", "비자카드"],
    ["", "", "", "", "", "", "", "", "", ""],  # 공란 추가
    [2024, 11, 13, 46, "대영모빌리티", 28531647, 3000, "아니오", "14:00", "비자카드"],
]

# 데이터를 엑셀에 작성
for row in data:
    sheet.append(row)

# 엑셀 파일 저장
wb.save("example.xlsx")
print("엑셀 파일이 생성되었습니다: example.xlsx")
